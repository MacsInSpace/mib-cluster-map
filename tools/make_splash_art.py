#!/usr/bin/env python3
"""Render player/splash/splash.svg into player/splash_art.h (RGBA bytes).

    python3 tools/make_splash_art.py      (needs rsvg-convert)

The header is committed, so a normal build needs neither this script nor
rsvg-convert. Only a change to the SVG does. The dot centre and orbit below
must match the SVG: the icon is placed at (100,4) scaled 100/48."""
import os, struct, subprocess, sys, tempfile, zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SVG = os.path.join(ROOT, "player", "splash", "splash.svg")
OUT = os.path.join(ROOT, "player", "splash_art.h")
S = 100.0 / 48.0
CX, CY = 100 + 24 * S, 4 + 24 * S       # icon centre in the art
ORBIT, DOT = 17 * S, 3.5 * S            # outer ring radius, dot radius


def decode_png(data):
    assert data[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    pos, idat, w = 8, b"", 0
    while pos < len(data):
        n, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        if kind == b"IHDR":
            w, h, depth, ctype, _, _, inter = struct.unpack(">IIBBBBB", body)
            assert depth == 8 and ctype == 6 and inter == 0, "want 8-bit RGBA, not interlaced"
        elif kind == b"IDAT":
            idat += body
        pos += 12 + n
    raw, bpp, stride = zlib.decompress(idat), 4, w * 4
    out, prev, i = bytearray(), bytearray(stride), 0
    for _ in range(h):
        f, line = raw[i], bytearray(raw[i + 1:i + 1 + stride]); i += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if f == 1: line[x] = (line[x] + a) & 255
            elif f == 2: line[x] = (line[x] + b) & 255
            elif f == 3: line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c; pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        out += line; prev = line
    return w, h, bytes(out)


def main():
    with tempfile.TemporaryDirectory() as t:
        png = os.path.join(t, "s.png")
        subprocess.check_call(["rsvg-convert", "-o", png, SVG])
        w, h, px = decode_png(open(png, "rb").read())
    lines = ["/* Generated by tools/make_splash_art.py from player/splash/splash.svg. */",
             "#define SPLASH_W %d" % w, "#define SPLASH_H %d" % h,
             "#define SPLASH_CX %.2ff" % CX, "#define SPLASH_CY %.2ff" % CY,
             "#define SPLASH_ORBIT %.2ff" % ORBIT, "#define SPLASH_DOT %.2ff" % DOT,
             "static const unsigned char kSplashArt[%d] = {" % len(px)]
    for i in range(0, len(px), 24):
        lines.append("    " + ",".join(str(b) for b in px[i:i + 24]) + ",")
    lines.append("};")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("%s: %dx%d, %d bytes" % (OUT, w, h, len(px)))


if __name__ == "__main__":
    sys.exit(main())
